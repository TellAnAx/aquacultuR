test_that( "nutrient nr", {
  
  expect_warning(nr(ibw=-1, fbw= 2, nut_start=3,nut_end=4))
  expect_warning(nr(ibw=1, fbw= -2, nut_start=3,nut_end=4))
  expect_warning(nr(ibw=1, fbw= 2, nut_start=-3,nut_end=4))
  expect_warning(nr(ibw=1, fbw= 2, nut_start=3,nut_end=-4))
  expect_warning(nr(ibw=0, fbw= 2, nut_start=3,nut_end=4))
  expect_warning(nr(ibw=1, fbw= 0, nut_start=3,nut_end=4))
  expect_warning(nr(ibw=1, fbw= 2, nut_start=0,nut_end=4))
  expect_warning(nr(ibw=1, fbw= 2, nut_start=3,nut_end=0))
  expect_error(nr(ibw= 'test', fbw= 2, nut_start=3,nut_end=4))
  expect_error(nr(ibw=1, fbw= 'test', nut_start=3,nut_end=4))
  expect_error(nr(ibw=1, fbw= 2, nut_start= 'test',nut_end=4))
  expect_error(nr(ibw=1, fbw= 2, nut_start=3,nut_end= 'test'))
  expect_error(nr(ibw=NA, fbw= 2, nut_start=3,nut_end=4))
  expect_error(nr(ibw=1, fbw= NA, nut_start=3,nut_end=4))
  expect_error(nr(ibw=1, fbw= 2, nut_start=NA,nut_end=4))
  expect_error(nr(ibw=1, fbw= 2, nut_start=3,nut_end=NA))
  expect_error(nr(ibw> fbw, nut_start=3,nut_end=4))
  expect_error(nr(ibw=1, fbw= 2, nut_start<nut_end))
})